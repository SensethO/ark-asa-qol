def call(name, owner, member, x, y, extra=None):
    reference = 'FunctionReference=(MemberParent="{}",MemberName="{}")'.format(
        CLASS_OF(owner), member)
    return Node(name, BP + "K2Node_CallFunction", x, y, [reference] + list(extra or []))


