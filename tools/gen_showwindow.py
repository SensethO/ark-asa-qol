_ids = itertools.count(1)


def guid():
    """32 hexadecimaux, uniques dans le collage ; le prefixe rend l'origine lisible"""
    return "A5A0C0DE{:024X}".format(next(_ids))


class Node:
    def __init__(self, name, cls, x, y, extra=None):
        self.name, self.cls, self.x, self.y = name, cls, x, y
        self.extra = list(extra or [])
        self.pins = []
        self.by_name = {}

    def pin(self, name, category, direction=None, sub=None, container=None,
            default=None, default_object=None, default_text=None, friendly=None,
            hidden=False, advanced=False, is_ref=False, is_const=False, autogen=None,
            dv_ignored=False):
        p = dict(id=guid(), name=name, category=category, direction=direction, sub=sub,
                 container=container, default=default, default_object=default_object,
                 default_text=default_text, friendly=friendly, hidden=hidden,
                 advanced=advanced, is_ref=is_ref, is_const=is_const, autogen=autogen,
                 dv_ignored=dv_ignored, links=[])
        self.pins.append(p)
        self.by_name[name] = p
        return p


def link(a, pin_a, b, pin_b):
    """Une liaison s'ecrit des deux cotes : Unreal ne la deduit pas d'un seul"""
    pa, pb = a.by_name[pin_a], b.by_name[pin_b]
    pa["links"].append((b.name, pb["id"]))
    pb["links"].append((a.name, pa["id"]))


TARGET_FRIENDLY = 'NSLOCTEXT("K2Node", "Target", "Target")'


def render_pin(p):
    bits = ["PinId=" + p["id"], 'PinName="{}"'.format(p["name"])]
    if p["friendly"]:
        bits.append("PinFriendlyName=" + p["friendly"])
    if p["direction"]:
        bits.append('Direction="{}"'.format(p["direction"]))
    bits.append('PinType.PinCategory="{}"'.format(p["category"]))
    bits.append('PinType.PinSubCategory=""')
    bits.append("PinType.PinSubCategoryObject=" +
                ('"{}"'.format(p["sub"]) if p["sub"] else "None"))
    bits.append("PinType.PinSubCategoryMemberReference=()")
    bits.append("PinType.PinValueType=()")
    bits.append("PinType.ContainerType=" + (p["container"] or "None"))
    bits.append("PinType.bIsReference=" + str(p["is_ref"]))
    bits.append("PinType.bIsConst=" + str(p["is_const"]))
    bits.append("PinType.bIsWeakPointer=False")
    bits.append("PinType.bIsUObjectWrapper=False")
    bits.append("PinType.bSerializeAsSinglePrecisionFloat=False")
    if p["default"] is not None:
        bits.append('DefaultValue="{}"'.format(p["default"]))
    if p["autogen"] is not None:
        bits.append('AutogeneratedDefaultValue="{}"'.format(p["autogen"]))
    if p["default_object"]:
        bits.append('DefaultObject="{}"'.format(p["default_object"]))
    if p["default_text"]:
        bits.append("DefaultTextValue=" + p["default_text"])
    if p["links"]:
        bits.append("LinkedTo=({})".format(
            "".join("{} {},".format(n, i) for n, i in p["links"])))
    bits.append("PersistentGuid=00000000000000000000000000000000")
    bits.append("bHidden=" + str(p["hidden"]))
    bits.append("bNotConnectable=False")
    bits.append("bDefaultValueIsReadOnly=False")
    bits.append("bDefaultValueIsIgnored=" + str(p["dv_ignored"]))
    bits.append("bAdvancedView=" + str(p["advanced"]))
    bits.append("bOrphanedPin=False")
    return "   CustomProperties Pin ({},)".format(",".join(bits))


def render(node):
    out = ['Begin Object Class={} Name="{}"'.format(node.cls, node.name)]
    out += ["   " + line for line in node.extra]
    out += ["   NodePosX={}".format(node.x),
            "   NodePosY={}".format(node.y),
            "   NodeGuid=" + guid()]
    out += [render_pin(p) for p in node.pins]
    out.append("End Object")
    return "\n".join(out)


